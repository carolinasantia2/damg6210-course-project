#!/usr/bin/env bash
# ---------- Build dist/ (Task 6: full assembly) ----------
# Assembles the two graded files from the per-table and per-cluster
# source files, in dependency order:
#   dist/create_database_and_schema.sql  <- CREATE DATABASE + drops + every CREATE TABLE
#   dist/insert_data.sql                 <- every INSERT
#
# Run from the repo root (macOS Terminal, Linux, or Git Bash on Windows):
#   bash scripts/build_dist.sh
#
# dist/ is generated output. Never edit it by hand: fix the source file
# under src/ or scripts/, then rerun this script.
set -euo pipefail

DB_NAME="AppointmentBookingDB"

# Explicit create order, parents first. NOT alphabetical: CancellationPolicy
# must follow Location, and Service must follow ServiceCategory.
TABLES=(
  "01_foundation/dbo.Business.sql"
  "01_foundation/dbo.Location.sql"
  "01_foundation/dbo.CancellationPolicy.sql"
  "01_foundation/dbo.LocationSocialMedia.sql"
  "01_foundation/dbo.ServiceCategory.sql"
  "01_foundation/dbo.Service.sql"
  "02_booking_core/dbo.Customer.sql"
  "02_booking_core/dbo.Appointment.sql"
  "02_booking_core/dbo.PaymentMethod.sql"
  "03_staff_time/dbo.Staff.sql"
  "03_staff_time/dbo.StaffService.sql"
  "03_staff_time/dbo.StaffAvailability.sql"
  "03_staff_time/dbo.TimeSlot.sql"
  "04_outcomes/dbo.Payment.sql"
  "04_outcomes/dbo.Cancellation.sql"
  "04_outcomes/dbo.Notification.sql"
  "05_appointment_service/dbo.AppointmentService.sql"
)

SEEDS=(
  "01_foundation_data.sql"
  "02_booking_core_data.sql"
  "03_staff_time_data.sql"
  "04_outcomes_data.sql"
  "05_appointment_service_data.sql"
)

DROP_SCRIPT="scripts/pre-deployment/drop_all_tables.sql"
CREATE_OUT="dist/create_database_and_schema.sql"
INSERT_OUT="dist/insert_data.sql"

# Fail early if any source file is missing.
missing=0
for f in "$DROP_SCRIPT" "${TABLES[@]/#/src/Tables/}" "${SEEDS[@]/#/scripts/post-deployment/}"; do
  if [[ ! -f "$f" ]]; then echo "Missing: $f" >&2; missing=1; fi
done
[[ $missing -eq 0 ]] || { echo "Build stopped. Nothing was written." >&2; exit 1; }

# Print a source file with its UTF-8 byte-order mark stripped (some editors
# save one, and a BOM in the middle of a combined file breaks parsing),
# followed by a newline so files never run together. The $'...' quoting
# and LC_ALL=C make this work with both macOS (BSD) sed and GNU sed.
emit() {
  echo
  echo "-- =================================================================="
  echo "-- Source: $1"
  echo "-- =================================================================="
  LC_ALL=C sed $'1s/^\xEF\xBB\xBF//' "$1"
  echo
}

mkdir -p dist

{
  echo "-- ---------- create_database_and_schema.sql ----------"
  echo "-- GENERATED by scripts/build_dist.sh. Do not edit by hand."
  echo "-- Creates the database if needed, drops every table (children first),"
  echo "-- then creates all 17 tables in dependency order. Safe to rerun."
  echo
  echo "USE master;"
  echo "GO"
  echo
  echo "IF DB_ID(N'$DB_NAME') IS NULL"
  echo "    CREATE DATABASE $DB_NAME;"
  echo "GO"
  echo
  echo "USE $DB_NAME;"
  echo "GO"
  emit "$DROP_SCRIPT"
  for t in "${TABLES[@]}"; do emit "src/Tables/$t"; done
} > "$CREATE_OUT"

{
  echo "-- ---------- insert_data.sql ----------"
  echo "-- GENERATED by scripts/build_dist.sh. Do not edit by hand."
  echo "-- Run AFTER create_database_and_schema.sql. Seeds all 17 tables in"
  echo "-- dependency order. Hardcoded FK values assume freshly created tables."
  echo
  echo "USE $DB_NAME;"
  echo "GO"
  echo
  echo "-- Guard: refuse to run against tables that already hold data, since"
  echo "-- the hardcoded FK values would point at the wrong rows. SET NOEXEC ON"
  echo "-- skips every remaining batch; it's switched back off at the end."
  echo "IF EXISTS (SELECT 1 FROM dbo.Business)"
  echo "BEGIN"
  echo "    RAISERROR('Tables already contain data. Run create_database_and_schema.sql first, then rerun this script.', 16, 1);"
  echo "    SET NOEXEC ON;"
  echo "END"
  echo "GO"
  for s in "${SEEDS[@]}"; do emit "scripts/post-deployment/$s"; done
  echo "SET NOEXEC OFF;"
  echo "GO"
} > "$INSERT_OUT"

echo "Built $CREATE_OUT ($(grep -c '^CREATE TABLE' "$CREATE_OUT") CREATE TABLE statements)"
echo "Built $INSERT_OUT ($(grep -c '^INSERT INTO' "$INSERT_OUT") INSERT statements)"